// Generates the module preload lists from the static import graph (no bundler; the files stay as they are).
//   - index.html: one <link rel="modulepreload"> per module of the first screen (src/app.js and everything it imports
//     statically), so the browser requests them all right after the HTML instead of one import level at a time.
//   - src/module-preload-map.js: for each lazy workspace, the modules it needs beyond the first screen; the workspace
//     prefetch adds those links at once before import(), which flattens that waterfall too. Likewise for the circuit
//     editor's own lazy parts (LAZY_MODULES, e.g. the result side that results-loader.js imports after the first screen).
// Usage: node scripts/gen-modulepreload.mjs          rewrite both outputs
//        node scripts/gen-modulepreload.mjs --check  exit 1 if either output is out of date (also run by check-boundaries)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { posix, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ENTRY = "app.js";
/** Lazy workspace name -> the module app.js imports dynamically for it. */
export const WORKSPACE_ENTRIES = { em: "em-controller.js", signals: "signals-course-controller.js", "circuit-course": "circuit-course-controller.js" };
/**
 * Lazy part of the circuit editor -> the module app.js imports dynamically for it, then the module workers it starts (their graph is
 * preloaded too, so the first worker finds its modules in the HTTP cache instead of fetching them one import level at a time).
 */
export const LAZY_ENTRIES = { results: ["result-views.js", "analysis-worker.js"] };
export const HEAD_START = "<!-- modulepreload: first-screen import graph, generated by `node scripts/gen-modulepreload.mjs`; do not edit by hand -->";
export const HEAD_END = "<!-- /modulepreload -->";
export const MAP_FILE = "src/module-preload-map.js";
const MAP_MODULE = MAP_FILE.slice("src/".length);

const STATIC_IMPORT = /\b(?:from\s*|import\s*)["'](\.{1,2}\/[^"']+)["']/g;
const DYNAMIC_IMPORT = /\bimport\s*\(\s*["'](\.{1,2}\/[^"'?]+)/g;

/** Imports of one module, as paths relative to src/ (posix). */
function importsOf(root, file) {
  if (file === MAP_MODULE && !existsSync(resolve(root, "src", file))) return { static: [], dynamic: [] }; // generated below
  const source = readFileSync(resolve(root, "src", file), "utf8");
  const dir = posix.dirname(file);
  const toFile = (path) => posix.normalize(posix.join(dir, path));
  return {
    static: [...source.matchAll(STATIC_IMPORT)].map((match) => toFile(match[1])),
    dynamic: [...source.matchAll(DYNAMIC_IMPORT)].map((match) => toFile(match[1])),
  };
}

/** Static closure of `entry` in breadth-first order (the order a browser discovers it), minus `skip`. */
export function staticClosure(root, entry, skip = new Set()) {
  const order = [entry], seen = new Set(order);
  for (let index = 0; index < order.length; index += 1) {
    for (const next of importsOf(root, order[index]).static) {
      if (seen.has(next)) continue;
      if (next !== MAP_MODULE && !existsSync(resolve(root, "src", next))) throw new Error(`${order[index]} imports missing module ${next}`);
      seen.add(next); order.push(next);
    }
  }
  return order.filter((file) => !skip.has(file));
}

export function computePreloads(root) {
  const startup = staticClosure(root, ENTRY);
  const dynamic = new Set(importsOf(root, ENTRY).dynamic);
  const missing = [...Object.values(WORKSPACE_ENTRIES), ...Object.values(LAZY_ENTRIES).map(([entry]) => entry)].filter((file) => !dynamic.has(file));
  if (missing.length) throw new Error(`${ENTRY} no longer imports ${missing.join(", ")} dynamically; update WORKSPACE_ENTRIES / LAZY_ENTRIES`);
  const first = new Set(startup);
  const beyondFirst = (files) => {
    const list = [];
    for (const file of files) list.push(...staticClosure(root, file, new Set([...first, ...list])));
    return list;
  };
  const workspaces = Object.fromEntries(Object.entries(WORKSPACE_ENTRIES).map(([name, file]) => [name, beyondFirst([file])]));
  const lazy = Object.fromEntries(Object.entries(LAZY_ENTRIES).map(([name, files]) => [name, beyondFirst(files)]));
  return { startup, workspaces, lazy };
}

export function renderHead(startup) {
  return [HEAD_START, ...startup.map((file) => `<link rel="modulepreload" href="src/${file}"/>`), HEAD_END].join("\n");
}

export function renderMap(workspaces, lazy = {}) {
  const lines = (lists) => Object.entries(lists).map(([name, files]) => `  ${JSON.stringify(name)}: [\n${files.map((file) => `    ${JSON.stringify(file)},`).join("\n")}\n  ],`);
  return [
    "// Generated by scripts/gen-modulepreload.mjs from the static import graph; do not edit by hand.",
    "// For each lazy workspace: the modules it needs beyond the first screen (paths relative to src/), in discovery order.",
    "export const WORKSPACE_MODULES = {",
    ...lines(workspaces),
    "};",
    "",
    "// For each lazy part of the circuit editor (results: result-views.js, see results-loader.js): the same, beyond the first screen.",
    "export const LAZY_MODULES = {",
    ...lines(lazy),
    "};",
    "",
  ].join("\n");
}

const BLOCK = new RegExp(`${HEAD_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${HEAD_END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);

/** The expected contents of both outputs; `html` is null when index.html has no preload block yet. */
function expectedOutputs(root) {
  const { startup, workspaces, lazy } = computePreloads(root);
  const htmlPath = resolve(root, "index.html");
  const html = readFileSync(htmlPath, "utf8");
  const head = renderHead(startup);
  let nextHtml;
  if (BLOCK.test(html)) nextHtml = html.replace(BLOCK, () => head);
  else {
    const anchor = /<link rel="stylesheet" href="styles\.css" ?\/>\n/;
    if (!anchor.test(html)) throw new Error("index.html: no modulepreload block and no styles.css link to place it after");
    nextHtml = html.replace(anchor, (match) => match + head + "\n");
  }
  return { htmlPath, html, nextHtml, mapPath: resolve(root, MAP_FILE), nextMap: renderMap(workspaces, lazy) };
}

/** Problems that mean the generated lists no longer match the import graph (empty when up to date). */
export function checkPreloads(root) {
  const out = expectedOutputs(root);
  const problems = [];
  if (out.html !== out.nextHtml) problems.push("index.html: the modulepreload list does not match the first-screen import graph; run `node scripts/gen-modulepreload.mjs`");
  const map = existsSync(out.mapPath) ? readFileSync(out.mapPath, "utf8") : null;
  if (map !== out.nextMap) problems.push(`${MAP_FILE}: the workspace preload lists do not match the import graph; run \`node scripts/gen-modulepreload.mjs\``);
  return problems;
}

export function writePreloads(root) {
  const out = expectedOutputs(root);
  const changed = [];
  if (out.html !== out.nextHtml) { writeFileSync(out.htmlPath, out.nextHtml); changed.push("index.html"); }
  if (!existsSync(out.mapPath) || readFileSync(out.mapPath, "utf8") !== out.nextMap) { writeFileSync(out.mapPath, out.nextMap); changed.push(MAP_FILE); }
  return changed;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve(process.env.CIRCUIT_LAB_ROOT || fileURLToPath(new URL("../", import.meta.url)));
  if (process.argv.includes("--check")) {
    const problems = checkPreloads(root);
    for (const problem of problems) console.error(problem);
    process.exitCode = problems.length ? 1 : 0;
  } else {
    const changed = writePreloads(root);
    const { startup, workspaces, lazy } = computePreloads(root);
    const counts = Object.entries({ ...lazy, ...workspaces }).map(([name, files]) => `${name} +${files.length}`).join(", ");
    console.log(`first screen: ${startup.length} modules; ${counts}; ${changed.length ? `updated ${changed.join(", ")}` : "already up to date"}`);
  }
}

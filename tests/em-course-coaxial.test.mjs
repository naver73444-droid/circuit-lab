test('reject bad radius order, epsilon, nonfinite/missing/non-numeric parameters', () => {
  const bad = [null, [], {}, { ...chargeParams, a: 0 }, { ...chargeParams, a: -.001 },
    { ...chargeParams, a: .004 }, { ...chargeParams, b: .0005 }, { ...chargeParams, c: .004 },
    { ...chargeParams, epsilonR: 0 }, { ...chargeParams, epsilonR: -2 },
    { ...chargeParams, lambda: NaN }, { ...chargeParams, lambda: Infinity },
    { ...chargeParams, lambda: '1e-9' }, { ...chargeParams, a: undefined }, { ...chargeParams, extra: -Infinity }];
  for (const params of bad) {
    const result = charge.evaluate(params, [.002, 0, 0]);
    assert.equal(result.status, 'invalid');
    assert.ok(result.reason);
    assert.deepEqual(result.vectors, {});
    assert.deepEqual(result.scalars, []);
  }
  assert.equal(voltage.evaluate({ ...voltageParams, voltage: Infinity }, [.002, 0, 0]).status, 'invalid');
});

test('reject malformed/nonfinite probes and unrepresentable derived results', () => {
  for (const point of [null, [], [0, 0], [0, 0, 0, 0], [NaN, 0, 0], [0, Infinity, 0], ['0', 0, 0]]) {
    assert.equal(charge.evaluate(chargeParams, point).status, 'invalid');
  }
  for (const [params, point] of [[{ ...chargeParams, lambda: 1e308 }, [.002, 0, 0]],
    [{ ...chargeParams, epsilonR: Number.MIN_VALUE }, [.002, 0, 0]],
    [chargeParams, [Number.MAX_VALUE, Number.MAX_VALUE, 0]]]) {
    const result = charge.evaluate(params, point);
    assert.equal(result.status, 'invalid');
    assert.deepEqual(result.vectors, {});
    finiteNumbers(result);
  }
});

test('bounded independent radial quadrature passes both fixtures and negative/zero drive', () => {
  for (const [experiment, params, control] of [[charge, chargeParams, 'lambda'], [voltage, voltageParams, 'voltage']]) {
    for (const multiplier of [1, -1, 0]) {
      const rows = experiment.verify({ ...params, [control]: multiplier * params[control] });
      assert.equal(rows.length, 1);
      assert.equal(rows[0].status, 'pass');
      assert.ok(rows[0].method.includes('quadrature'));
      assert.ok(Number.isFinite(rows[0].actual));
      assert.ok(Number.isFinite(rows[0].expected));
    }
  }
});

test('invalid or numerically inseparable gap verification is explicitly skipped', () => {
  for (const params of [{ ...chargeParams, b: .0001 }, { ...chargeParams, lambda: Infinity },
    { ...chargeParams, b: .0010000000000000002 }]) {
    const rows = charge.verify(params);
    assert.equal(rows[0].status, 'skipped');
    assert.ok(rows[0].reason);
    assert.equal(rows[0].actual, undefined);
  }
});

test('review regression b/a=20 converges without changing evaluation or tolerances', () => {
  for (const [experiment, control, drive] of [[voltage, 'voltage', 100], [charge, 'lambda', 1e-9]]) {
    for (const sign of [1, -1, 0]) {
      const params = { a: .001, b: .020, c: .021, epsilonR: 2.5, [control]: sign * drive };
      const before = experiment.evaluate(params, [.002, 0, 0]);
      const [row] = experiment.verify(params);
      assert.equal(row.status, 'pass', row.reason);
      assert.equal(row.absTolerance, 1e-10);
      assert.equal(row.relTolerance, 2e-6);
      assert.ok(row.method.includes('convergence'));
      assert.ok(row.sampleCount <= 1025);
      assert.ok(row.estimatedError <= row.absTolerance + row.relTolerance * Math.abs(row.expected));
      assert.deepEqual(experiment.evaluate(params, [.002, 0, 0]), before);
    }
  }
});

test('unresolved wide-gap verification reports numerical nonconvergence instead of physical fail', () => {
  const params = { a: 1e-6, b: 1, c: 1.1, epsilonR: 2.5, voltage: 100 };
  const evaluated = voltage.evaluate(params, [.002, 0, 0]);
  assert.equal(evaluated.status, 'valid');
  const [row] = voltage.verify(params);
  assert.equal(row.status, 'skipped');
  assert.ok(row.reason.includes('수렴'));
  assert.ok(row.sampleCount <= 1025);
  assert.ok(Number.isFinite(row.actual));
  assert.ok(Number.isFinite(row.estimatedError));
  assert.equal(row.expected, 100);
});
